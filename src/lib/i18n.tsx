type Vars = Record<string, string | number>;

const interpolate = (text: string, vars?: Vars): string =>
  vars ? text.replace(/\{(\w+)\}/g, (whole, name) => (name in vars ? String(vars[name]) : whole)) : text;

export type TFunction = (key: string, vars?: Vars) => string;

export const makeT =
  (lang: Language): TFunction =>
  (key, vars) =>
    interpolate(lang === "id" ? ID[key] ?? key : key, vars);

const LanguageContext = createContext<{ lang: Language; t: TFunction }>({
  lang: "en",
  t: makeT("en"),
});

export const LanguageProvider = LanguageContext.Provider;

export const useT = () => useContext(LanguageContext);
